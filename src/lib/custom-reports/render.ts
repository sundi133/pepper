/**
 * Final output for a custom report: the standalone HTML page (shared report
 * shell, sanitized body, AI-generation footer) and a PDF drawn with pdfkit
 * from the same Markdown.
 */
import {
  escapeHtml,
  loadPdfKit,
  renderReportShell,
} from "@/lib/reports/report-html";
import { inlineToText, parseMarkdown, renderMarkdownHtml, stripRawHtml, type MdBlock } from "./markdown";
import { sanitizeReportHtml } from "./sanitize-html";

export interface ReportMeta {
  title: string;
  templateName: string;
  projectName: string;
  scanId: string;
  generatedAt: Date;
  model: string;
}

/** The provenance line every custom report carries. */
export function aiFooter(meta: Pick<ReportMeta, "scanId" | "generatedAt" | "model">): string {
  return (
    `This report was generated by AI from Pepper scan ${meta.scanId} at ` +
    `${meta.generatedAt.toISOString().replace("T", " ").slice(0, 19)} UTC with model ${meta.model}. ` +
    "Finding references were checked against the scan data; review before relying on it."
  );
}

export function buildCustomReportHtml(markdown: string, meta: ReportMeta): string {
  const body = sanitizeReportHtml(renderMarkdownHtml(markdown));
  return renderReportShell({
    title: `${meta.title} — ${meta.projectName}`,
    eyebrow: `Custom report · ${meta.templateName}`,
    heading: meta.title,
    subtitle: `${escapeHtml(meta.projectName)} · scan ${escapeHtml(meta.scanId)}`,
    body: `<style>blockquote{border-left:3px solid #e5e7eb;padding-left:.8rem;color:#4b5563;margin:.6rem 0}pre{background:#f3f4f6;padding:.6rem;border-radius:6px;overflow-x:auto;font-size:.8rem;margin:.6rem 0}code{font-size:.85em}ul,ol{margin:.3rem 0 .8rem 1.3rem}h1{font-size:1.4rem;margin:1.5rem 0 .6rem}h4,h5,h6{font-size:.92rem;margin:1rem 0 .4rem}hr{border:0;border-top:1px solid #e5e7eb;margin:1.2rem 0}</style>${body}`,
    footer: aiFooter(meta),
  });
}

/** Markdown as downloaded: the report plus the provenance footer. */
export function buildCustomReportMarkdown(markdown: string, meta: ReportMeta): string {
  return `# ${meta.title}\n\n_${meta.projectName} · scan ${meta.scanId}_\n\n${stripRawHtml(markdown).trim()}\n\n---\n\n_${aiFooter(meta)}_\n`;
}

const C = { text: "#1a1a2e", muted: "#6b7280", header: "#1e3a5f", border: "#e5e7eb", light: "#f9fafb", white: "#ffffff" };

export function buildCustomReportPdf(markdown: string, meta: ReportMeta): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const PDFDocument = loadPdfKit();
      const doc = new PDFDocument({
        size: "A4",
        margins: { top: 50, bottom: 50, left: 50, right: 50 },
        info: { Title: `${meta.title} — ${meta.projectName}`, Author: "Pepper SAST", Subject: meta.templateName },
      });
      const chunks: Buffer[] = [];
      doc.on("data", (c: Buffer) => chunks.push(c));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const pageW = 595.28;
      const x0 = 50;
      const w = pageW - 100;
      const bottom = 780;
      let y = 0;
      const ensure = (h: number) => {
        if (y + h > bottom) {
          doc.addPage();
          y = 50;
        }
      };
      const text = (s: string, size: number, color: string, opts: { indent?: number; font?: string } = {}) => {
        doc.font(opts.font ?? "Helvetica").fontSize(size);
        const width = w - (opts.indent ?? 0);
        const h = doc.heightOfString(s, { width });
        ensure(Math.min(h, 200));
        doc.fillColor(color).text(s, x0 + (opts.indent ?? 0), y, { width });
        y = doc.y + 4;
      };

      doc.rect(0, 0, pageW, 110).fill(C.header);
      doc.fontSize(8).fillColor("#94a3b8").text(`CUSTOM REPORT · ${meta.templateName.toUpperCase()}`, x0, 28, { width: w });
      doc.fontSize(20).fillColor(C.white).text(meta.title, x0, 44, { width: w, height: 30, ellipsis: true });
      doc.fontSize(9).fillColor("#cbd5e1").text(`${meta.projectName} · scan ${meta.scanId}`, x0, 80, { width: w });
      y = 130;

      const drawTable = (b: Extract<MdBlock, { type: "table" }>) => {
        const cols = Math.max(b.header.length, 1);
        const colW = w / cols;
        const row = (cells: string[], header: boolean) => {
          doc.font(header ? "Helvetica-Bold" : "Helvetica").fontSize(7.5);
          const texts = cells.map((c) => inlineToText(c));
          const h = Math.max(...texts.map((t) => doc.heightOfString(t, { width: colW - 8 })), 8) + 8;
          ensure(h);
          if (header) doc.rect(x0, y, w, h).fill(C.header);
          texts.forEach((t, i) => {
            doc.fillColor(header ? C.white : C.text).text(t, x0 + i * colW + 4, y + 4, { width: colW - 8 });
          });
          y += h;
          doc.moveTo(x0, y).lineTo(x0 + w, y).strokeColor(C.border).lineWidth(0.5).stroke();
        };
        row(b.header, true);
        b.rows.forEach((r) => row(r, false));
        y += 8;
      };

      const draw = (blocks: MdBlock[], indent = 0) => {
        for (const b of blocks) {
          switch (b.type) {
            case "heading": {
              y += b.level <= 2 ? 10 : 4;
              ensure(40);
              if (b.level <= 2) doc.rect(x0 + indent, y, 4, 14).fill(C.header);
              text(inlineToText(b.text), b.level <= 1 ? 14 : b.level === 2 ? 12 : 10.5, C.text, {
                indent: indent + (b.level <= 2 ? 10 : 0),
                font: "Helvetica-Bold",
              });
              y += 2;
              break;
            }
            case "paragraph":
              text(inlineToText(b.text), 9.5, C.text, { indent });
              y += 3;
              break;
            case "list":
              b.items.forEach((it, i) => {
                text(`${b.ordered ? `${i + 1}.` : "•"}  ${inlineToText(it.text)}`, 9.5, C.text, { indent: indent + 8 });
                if (it.children.length) draw(it.children, indent + 16);
              });
              y += 3;
              break;
            case "table":
              drawTable(b);
              break;
            case "quote":
              draw(b.blocks, indent + 12);
              break;
            case "code":
              text(b.text, 8, C.muted, { indent: indent + 6, font: "Courier" });
              y += 3;
              break;
            case "hr":
              ensure(12);
              doc.moveTo(x0, y + 4).lineTo(x0 + w, y + 4).strokeColor(C.border).lineWidth(0.5).stroke();
              y += 12;
              break;
          }
        }
      };
      draw(parseMarkdown(stripRawHtml(markdown)));

      y += 12;
      text(aiFooter(meta), 7.5, C.muted);
      doc.end();
    } catch (e) {
      reject(e);
    }
  });
}
