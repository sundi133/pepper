import { describe, expect, it } from "vitest";
import { renderMarkdownHtml } from "./markdown";
import { sanitizeReportHtml } from "./sanitize-html";
import { buildCustomReportHtml, buildCustomReportMarkdown } from "./render";

describe("Markdown rendering of model output", () => {
  it("never passes raw HTML or script through", () => {
    const html = renderMarkdownHtml(
      '## Risks\n<script>fetch("https://evil.example")</script>\n<img src=x onerror=alert(1)>\nText <b>bold</b> & `<code>`',
    );
    expect(html).not.toMatch(/<script|<img|onerror|evil\.example/);
    expect(html).toContain("<h2>Risks</h2>");
    expect(html).toContain("&amp;");
    expect(html).toContain("<code>&lt;code&gt;</code>");
  });

  it("keeps http(s) links only and turns images into their alt text", () => {
    const html = renderMarkdownHtml(
      "[ok](https://owasp.org/x) [bad](javascript:alert(1)) [data](data:text/html,x) ![diagram](https://tracker.example/p.png)",
    );
    expect(html).toContain('<a href="https://owasp.org/x" rel="noopener noreferrer nofollow">ok</a>');
    expect(html).not.toMatch(/javascript:|data:text|<img|tracker\.example/);
    expect(html).toContain("diagram");
  });

  it("renders tables, lists and emphasis", () => {
    const html = renderMarkdownHtml("| A | B |\n| --- | --- |\n| **x** | *y* |\n\n- one\n- two\n\n1. first");
    expect(html).toContain("<table><thead><tr><th>A</th><th>B</th></tr></thead><tbody><tr><td><strong>x</strong></td><td><em>y</em></td></tr></tbody></table>");
    expect(html).toContain("<ul><li>one</li><li>two</li></ul>");
    expect(html).toContain("<ol><li>first</li></ol>");
  });
});

describe("sanitizeReportHtml", () => {
  it("drops script-like elements with their content", () => {
    const out = sanitizeReportHtml("<p>a</p><script>alert(1)</script><style>p{}</style><iframe src=x>y</iframe><p>b</p>");
    expect(out).toBe("<p>a</p><p>b</p>");
  });

  it("drops event handlers, styles and resource-loading elements", () => {
    const out = sanitizeReportHtml(
      '<p onclick="x()" style="background:url(https://e.example)">t</p><img src="https://e.example/a.png"><link rel=stylesheet href=//e.example><svg onload=alert(1)><circle/></svg>',
    );
    expect(out).toBe("<p>t</p>");
  });

  it("allows only http(s) hrefs, including against entity-encoded schemes", () => {
    expect(sanitizeReportHtml('<a href="javascript:alert(1)">x</a>')).toBe("<a>x</a>");
    expect(sanitizeReportHtml('<a href="jav&#x61;script:alert(1)">x</a>')).toBe("<a>x</a>");
    expect(sanitizeReportHtml('<a href="https://nvd.nist.gov/">x</a>')).toBe(
      '<a href="https://nvd.nist.gov/" rel="noopener noreferrer nofollow">x</a>',
    );
  });

  it("keeps formatting and balances unclosed tags", () => {
    expect(sanitizeReportHtml("<h2>T</h2><ul><li><strong>a")).toBe("<h2>T</h2><ul><li><strong>a</strong></li></ul>");
    expect(sanitizeReportHtml("1 < 2 and </p> stray")).toBe("1 &lt; 2 and  stray");
  });
});

describe("custom report page", () => {
  const meta = {
    title: "Status",
    templateName: "Monthly",
    projectName: "payments<x>",
    scanId: "scan_123",
    generatedAt: new Date("2026-10-16T10:00:00Z"),
    model: "gpt-4o-mini",
  };

  it("is a script-free page with the AI provenance footer", () => {
    const html = buildCustomReportHtml('## Summary\n<script>alert(1)</script>Two [F1] findings. <iframe src="https://x"></iframe>', meta);
    expect(html).not.toMatch(/<script|<iframe|<img|<link/i);
    expect(html).toContain("generated by AI from Pepper scan scan_123 at 2026-10-16 10:00:00 UTC with model gpt-4o-mini");
    expect(html).toContain("payments&lt;x&gt;");
  });

  it("adds the same footer to the Markdown download", () => {
    const md = buildCustomReportMarkdown("## Summary\nText", meta);
    expect(md).toMatch(/^# Status/);
    expect(md).toContain("scan scan_123");
    expect(md).toContain("with model gpt-4o-mini");
  });
});
